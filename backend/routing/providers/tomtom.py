"""TomTom truck routing and place search.

Quota-conscious by design (free tier ≈ 2,500 requests/day):
- one routing call returns up to 5 alternatives; extra detour calls only happen
  when fewer than 3 distinct, reasonable routes come back;
- routes and searches are cached, so re-sampling at another interval is free.
"""

from __future__ import annotations

import hashlib
import math
from dataclasses import dataclass
from datetime import datetime
from urllib.parse import quote

import httpx
from django.conf import settings
from django.core.cache import cache

from ..geometry import LatLon, cumulative_distances
from ..sampling import RouteGeometry

ROUTING_URL = "https://api.tomtom.com/routing/1/calculateRoute/{locations}/json"
SEARCH_URL = "https://api.tomtom.com/search/2/search/{query}.json"
KG_PER_LB = 0.45359237

ROUTES_WANTED = 3
MAX_TIME_RATIO = 1.5  # drop alternatives slower than 1.5× the fastest
MAX_OVERLAP = 0.7  # routes sharing more than this share of 0.1° cells are duplicates
DETOUR_OFFSET = 0.15  # via-point offset from the midpoint, as a share of crow-fly length
OVERLAP_CELL_DEG = 0.1

ROUTE_CACHE_TTL_S = 10 * 60  # traffic-aware, so keep it short
SEARCH_CACHE_TTL_S = 24 * 60 * 60


class RoutingProviderError(Exception):
    """Provider unreachable or returned an error. `code` is safe to show the UI."""

    def __init__(self, message: str, code: str = "routing_unavailable"):
        super().__init__(message)
        self.code = code


@dataclass(frozen=True)
class Route:
    geometry: RouteGeometry
    distance_m: float
    duration_s: float
    traffic_delay_s: float
    via_detour: bool  # generated by us rather than returned as a TomTom alternative


@dataclass(frozen=True)
class Place:
    label: str
    lat: float
    lon: float


def _get(client: httpx.Client, url: str, params: dict | list) -> dict:
    if not settings.TOMTOM_API_KEY:
        raise RoutingProviderError("TOMTOM_API_KEY is not configured", code="not_configured")
    try:
        response = client.get(url, params=[("key", settings.TOMTOM_API_KEY), *_items(params)])
    except httpx.HTTPError as exc:
        raise RoutingProviderError(f"TomTom request failed: {type(exc).__name__}") from exc
    if response.status_code == 400 and "NO_ROUTE_FOUND" in response.text:
        raise RoutingProviderError("No truck route between these points", code="no_route")
    if response.status_code == 429:
        raise RoutingProviderError("TomTom rate limit reached", code="rate_limited")
    if response.status_code >= 400:
        # Never echo the response URL: it contains the API key.
        raise RoutingProviderError(f"TomTom returned HTTP {response.status_code}")
    return response.json()


def _items(params: dict | list) -> list[tuple[str, str]]:
    return list(params.items()) if isinstance(params, dict) else list(params)


# ---------------------------------------------------------------- search


def search_places(query: str, limit: int = 6) -> list[Place]:
    query = " ".join(query.split())
    digest = hashlib.sha1(query.lower().encode(), usedforsecurity=False).hexdigest()
    key = f"tt:search:v1:{digest}:{limit}"
    if (hit := cache.get(key)) is not None:
        return hit
    params = {
        "typeahead": "true",
        "limit": limit,
        "countrySet": "US",
        "idxSet": "Geo,PAD,Addr,POI",
    }
    with httpx.Client(timeout=settings.PROVIDER_TIMEOUT_S) as client:
        data = _get(client, SEARCH_URL.format(query=quote(query, safe="")), params)
    places = [
        Place(
            label=r.get("address", {}).get("freeformAddress") or r.get("poi", {}).get("name", ""),
            lat=r["position"]["lat"],
            lon=r["position"]["lon"],
        )
        for r in data.get("results", [])
        if "position" in r
    ]
    cache.set(key, places, SEARCH_CACHE_TTL_S)
    return places


# ---------------------------------------------------------------- routing


def _parse_route(raw: dict, via_detour: bool = False) -> Route:
    coords: list[LatLon] = []
    for leg in raw["legs"]:
        pts = [(p["latitude"], p["longitude"]) for p in leg["points"]]
        # Consecutive legs share their joining point.
        coords.extend(pts[1:] if coords and pts and pts[0] == coords[-1] else pts)

    summary = raw["summary"]
    length_m = float(summary["lengthInMeters"])
    duration_s = float(summary["travelTimeInSeconds"])

    # Scale our haversine distances to TomTom's official length so mile markers match the summary.
    dists = cumulative_distances(coords)
    scale = length_m / dists[-1] if dists[-1] else 1.0
    dists = [d * scale for d in dists]

    times = _interpolate_times(dists, raw.get("progress") or [], duration_s)
    return Route(
        geometry=RouteGeometry(tuple(coords), tuple(dists), tuple(times)),
        distance_m=length_m,
        duration_s=duration_s,
        traffic_delay_s=float(summary.get("trafficDelayInSeconds", 0)),
        via_detour=via_detour,
    )


def _interpolate_times(dists: list[float], progress: list[dict], duration_s: float) -> list[float]:
    """Travel time at every vertex. TomTom's `progress` is sparse (≈1 entry per 100 points);
    between entries we assume constant speed. Without it, constant speed end to end."""
    anchors = sorted(
        (p["pointIndex"], float(p["travelTimeInSeconds"]))
        for p in progress
        if "pointIndex" in p and "travelTimeInSeconds" in p and p["pointIndex"] < len(dists)
    )
    if not anchors or anchors[0][0] != 0:
        anchors.insert(0, (0, 0.0))
    if anchors[-1][0] != len(dists) - 1:
        anchors.append((len(dists) - 1, duration_s))

    times = [0.0] * len(dists)
    for (i0, t0), (i1, t1) in zip(anchors, anchors[1:], strict=False):
        span = dists[i1] - dists[i0]
        for i in range(i0, i1 + 1):
            frac = (dists[i] - dists[i0]) / span if span else 0.0
            times[i] = t0 + (t1 - t0) * frac
    return times


def _cells(route: Route) -> set[tuple[int, int]]:
    return {
        (math.floor(lat / OVERLAP_CELL_DEG), math.floor(lon / OVERLAP_CELL_DEG))
        for lat, lon in route.geometry.coords
    }


def _overlap(a: set, b: set) -> float:
    return len(a & b) / len(a | b) if a or b else 1.0


def select_routes(candidates: list[Route], wanted: int = ROUTES_WANTED) -> list[Route]:
    """Keep provider order; drop slow outliers and near-duplicates."""
    if not candidates:
        return []
    fastest = min(r.duration_s for r in candidates)
    chosen: list[Route] = []
    chosen_cells: list[set] = []
    for route in candidates:
        if route.duration_s > fastest * MAX_TIME_RATIO:
            continue
        cells = _cells(route)
        if any(_overlap(cells, other) > MAX_OVERLAP for other in chosen_cells):
            continue
        chosen.append(route)
        chosen_cells.append(cells)
        if len(chosen) == wanted:
            break
    return chosen


def detour_points(origin: LatLon, destination: LatLon) -> list[LatLon]:
    """Via-points either side of the crow-fly midpoint, used to force distinct corridors."""
    mid_lat = (origin[0] + destination[0]) / 2
    mid_lon = (origin[1] + destination[1]) / 2
    cos_lat = math.cos(math.radians(mid_lat))
    dlat = destination[0] - origin[0]
    dlon = (destination[1] - origin[1]) * cos_lat  # equirectangular, fine at this scale
    length = math.hypot(dlat, dlon)
    if length == 0:
        return []
    points = []
    for side in (1, -1):
        offset = DETOUR_OFFSET * length * side
        points.append(
            (mid_lat - dlon / length * offset, mid_lon + dlat / length * offset / cos_lat)
        )
    return points


def _routing_params(depart_at: datetime | None, weight_lb: float) -> list[tuple[str, str]]:
    params = [
        ("travelMode", "truck"),
        ("vehicleCommercial", "true"),
        ("vehicleWeight", str(round(weight_lb * KG_PER_LB))),
        ("traffic", "true"),
        ("routeRepresentation", "polyline"),
        ("extendedRouteRepresentation", "travelTime"),
    ]
    if depart_at is not None:
        params.append(("departAt", depart_at.isoformat(timespec="seconds")))
    return params


def _locations(*points: LatLon) -> str:
    return ":".join(f"{lat:.5f},{lon:.5f}" for lat, lon in points)


def get_routes(
    origin: LatLon, destination: LatLon, depart_at: datetime | None, weight_lb: float
) -> list[Route]:
    """Up to 3 distinct truck routes, fastest-first as TomTom orders them.

    `depart_at=None` means "now". Cached for 10 minutes per (points, 15-min slot, 1,000-lb bucket).
    """
    slot = depart_at.replace(minute=depart_at.minute // 15 * 15, second=0) if depart_at else None
    key = "tt:routes:v1:{}:{}:{}".format(
        _locations(origin, destination),
        slot.isoformat() if slot else "now",
        round(weight_lb / 1000),
    )
    if (hit := cache.get(key)) is not None:
        return hit

    base = _routing_params(depart_at, weight_lb)
    with httpx.Client(timeout=settings.PROVIDER_TIMEOUT_S) as client:
        data = _get(
            client,
            ROUTING_URL.format(locations=_locations(origin, destination)),
            [*base, ("maxAlternatives", "5"), ("alternativeType", "anyRoute")],
        )
        candidates = [_parse_route(r) for r in data.get("routes", [])]
        routes = select_routes(candidates)

        for via in detour_points(origin, destination) if len(routes) < ROUTES_WANTED else []:
            try:
                detour = _get(
                    client, ROUTING_URL.format(locations=_locations(origin, via, destination)), base
                )
            except RoutingProviderError:
                continue  # a detour is a nice-to-have; never fail the trip over it
            candidates += [_parse_route(r, via_detour=True) for r in detour.get("routes", [])]
            routes = select_routes(candidates)
            if len(routes) == ROUTES_WANTED:
                break

    if not routes:
        raise RoutingProviderError("No truck route between these points", code="no_route")
    cache.set(key, routes, ROUTE_CACHE_TTL_S)
    return routes
